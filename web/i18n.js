export function t(key, locale = document.documentElement.lang || 'es') {
  return messages[locale]?.[key] || messages.es[key] || key;
}

export function applyTranslations(locale = 'es') {
  document.documentElement.lang = locale;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = messages[locale]?.[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-text]').forEach((element) => {
    const value = messages[locale]?.[element.dataset.i18nText];
    if (value) {
      const textNode = [...element.childNodes].find(
        (node) => node.nodeType === Node.TEXT_NODE,
      );
      if (textNode) textNode.nodeValue = value;
    }
  });
  for (const [attribute, keyAttribute] of [
    ['aria-label', 'data-i18n-aria'],
    ['title', 'data-i18n-title'],
    ['placeholder', 'data-i18n-placeholder'],
  ]) {
    document.querySelectorAll(`[${keyAttribute}]`).forEach((element) => {
      const value = messages[locale]?.[element.getAttribute(keyAttribute)];
      if (value) element.setAttribute(attribute, value);
    });
  }
}
